export type IconName = keyof typeof RAW;
const cache = new Map<string, string>();
function clean(name: string): string {
  let s = cache.get(name);
  if (!s) {
    s = (RAW[name] ?? '')
      .replace(/<!--[\s\S]*?-->/g, '')
      // largeur, hauteur et classe retirées de la seule balise <svg> (les <rect> gardent les leurs)
      .replace(/<svg[^>]*>/, (tag) => tag.replace(/\s(width|height|class)="[^"]*"/g, '').replace('<svg', '<svg aria-hidden="true" focusable="false"'))
      .replace(/\n\s*/g, '');
    cache.set(name, s);
  }
  return s;
}

export function Icon({name, size = 20, class: cls = ''}: {name: string; size?: number; class?: string}) {
  return <span class={`ic ${cls}`} style={{width: size, height: size}} dangerouslySetInnerHTML={{__html: clean(name)}} />;
}
